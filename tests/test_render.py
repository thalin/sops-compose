import yaml

from conftest import K, git_add, write

from sops_compose.config import load
from sops_compose.render import render


def rules(root):
    return yaml.safe_load((root / ".sops.yaml").read_text())["creation_rules"]


def test_render_resolves_references(repo, run):
    code, out, _ = run(repo, "render")
    assert code == 0 and "wrote .sops.yaml" in out
    r = rules(repo)
    assert [x["path_regex"] for x in r] == [
        r"^secrets\.yaml$", r"systems/.*/sshkeys/.*\.yaml$", "systems/alpha/.*$", "systems/beta/.*$",
    ]
    # `all` is every key, in file order (namespace files sorted by name).
    assert r[0]["age"] == [K["alpha"], K["beta"], K["gamma"], K["token1"], K["token2"], K["admin"]]
    # Groups expand, namespaces expand to every key under them.
    assert r[1]["age"] == [K["admin"], K["token1"], K["token2"]]
    assert r[2]["age"] == [K["admin"], K["token1"], K["token2"], K["alpha"]]


def test_render_passes_other_fields_through(repo, run):
    run(repo, "render")
    assert rules(repo)[3]["encrypted_regex"] == "^(data|stringData)$"


def test_render_labels_keys_and_has_header(repo, run):
    run(repo, "render")
    text = (repo / ".sops.yaml").read_text()
    assert text.startswith("# GENERATED by sops-compose")
    assert f"{K['alpha']}" in text and "# hosts.alpha" in text
    assert "# users.admin.laptop" in text


def test_render_is_deterministic(repo, run):
    run(repo, "render")
    first = (repo / ".sops.yaml").read_text()
    assert render(load(repo)) == first
    code, out, _ = run(repo, "render")
    assert code == 0 and "up to date" in out


def test_duplicates_are_removed(repo, run):
    write(repo, "sops/rules.yaml", """
        - path_regex: x
          age: [me, users.admin.laptop, users]
    """)
    write(repo, "x", "")
    git_add(repo, "x")
    run(repo, "render")
    assert rules(repo)[0]["age"] == [K["admin"], K["token1"], K["token2"]]


def test_nested_groups(repo, run):
    write(repo, "sops/groups.yaml", """
        me: [users.admin, tokens]
        alpha-team: [me, hosts.alpha]
    """)
    write(repo, "sops/rules.yaml", r"""
        - path_regex: ^secrets\.yaml$
          age: [alpha-team, hosts.gamma]
    """)
    run(repo, "render")
    assert rules(repo)[0]["age"] == [K["admin"], K["token1"], K["token2"], K["alpha"], K["gamma"]]
